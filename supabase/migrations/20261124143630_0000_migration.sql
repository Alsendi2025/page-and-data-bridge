/*
# Initialize core schema for Taqa Plus solar platform

1. Roles & Auth
- Creates `app_role` enum (admin, moderator, user) and `user_roles` table
- Creates `has_role()` helper function (SECURITY DEFINER)
- Creates `admin_emails` table for auto-granting admin on verified email
- Creates trigger `on_auth_user_verified_grant_admin` to auto-promote verified admin emails

2. Products table
3. Articles table
4. Projects table (saved solar system designs)
5. Quote requests table
6. Legacy user map

7. Security
- RLS enabled on all tables
- Grants and policies enforce admin role for writes via has_role()
*/

-- Roles enum
DO $$ BEGIN
  CREATE TYPE public.app_role AS ENUM ('admin', 'moderator', 'user');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- user_roles table
CREATE TABLE IF NOT EXISTS public.user_roles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade not null,
  role public.app_role not null,
  unique (user_id, role)
);
grant select on public.user_roles to authenticated;
grant all on public.user_roles to service_role;
alter table public.user_roles enable row level security;

-- has_role function (must exist before policies that reference it)
CREATE OR REPLACE FUNCTION public.has_role(_user_id uuid, _role public.app_role)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.user_roles where user_id = _user_id and role = _role)
$$;

-- user_roles policies
DROP POLICY IF EXISTS "Users can read their own roles" ON public.user_roles;
create policy "Users can read their own roles" on public.user_roles
  for select to authenticated using (auth.uid() = user_id);
DROP POLICY IF EXISTS "Admins can read all roles" ON public.user_roles;
create policy "Admins can read all roles" on public.user_roles
  for select to authenticated using (public.has_role(auth.uid(), 'admin'));

-- admin_emails table
CREATE TABLE IF NOT EXISTS public.admin_emails (
  email text primary key,
  created_at timestamptz not null default now()
);
grant all on public.admin_emails to service_role;
alter table public.admin_emails enable row level security;

-- grant_admin_for_verified_email function
CREATE OR REPLACE FUNCTION public.grant_admin_for_verified_email()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.email_confirmed_at is not null
     and exists (select 1 from public.admin_emails a where lower(a.email) = lower(new.email)) then
    insert into public.user_roles (user_id, role) values (new.id, 'admin')
    on conflict (user_id, role) do nothing;
  end if;
  return new;
end;
$$;

DROP TRIGGER IF EXISTS on_auth_user_verified_grant_admin ON auth.users;
create trigger on_auth_user_verified_grant_admin
  after insert or update of email_confirmed_at, email on auth.users
  for each row execute function public.grant_admin_for_verified_email();

-- Products
CREATE TABLE IF NOT EXISTS public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  brand text not null default '',
  category text not null default 'panel',
  power_w numeric,
  capacity_ah numeric,
  capacity_wh numeric,
  voltage_v numeric,
  current_a numeric,
  price_yer numeric,
  image_url text,
  description text,
  specs jsonb,
  in_stock boolean not null default true,
  created_at timestamptz not null default now()
);
grant select on public.products to anon;
grant select, insert, update, delete on public.products to authenticated;
grant all on public.products to service_role;
alter table public.products enable row level security;
DROP POLICY IF EXISTS "Anyone can view products" ON public.products;
create policy "Anyone can view products" on public.products for select to anon, authenticated using (true);
DROP POLICY IF EXISTS "Admins insert products" ON public.products;
create policy "Admins insert products" on public.products for insert to authenticated with check (public.has_role(auth.uid(), 'admin'));
DROP POLICY IF EXISTS "Admins update products" ON public.products;
create policy "Admins update products" on public.products for update to authenticated using (public.has_role(auth.uid(), 'admin')) with check (public.has_role(auth.uid(), 'admin'));
DROP POLICY IF EXISTS "Admins delete products" ON public.products;
create policy "Admins delete products" on public.products for delete to authenticated using (public.has_role(auth.uid(), 'admin'));

