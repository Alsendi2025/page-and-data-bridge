  id bigint generated by default as identity primary key,
  name text not null,
  brand text not null default '',
  category text not null default 'panel',
  power_w numeric,
  capacity_ah numeric,
  capacity_wh numeric,
  voltage_v numeric,
  current_a numeric,
  price_yer numeric,
  image_url text,
  description text,
  specs jsonb,
  in_stock boolean not null default true,
